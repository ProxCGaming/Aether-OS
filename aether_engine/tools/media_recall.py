"""``media_recall`` tool (Epic 8, E8-4.3; grill Q25).

Agents find media the user shared or earlier tasks generated by
describing what it shows — "the red bicycle photo", "that schema
diagram" — and get back entries carrying their session/message
references, so a recalled item can be jumped to, re-shown, or
built on.

Recall is the MediaStore's hybrid search (lexical + semantic over
the analysis embeddings, E8-4.3). The query is embedded through
the unified embedder (E8-3.2 — same model, same circuit breaker
as episodic memory and workspace search); when the endpoint is
down the search degrades to lexical matching and the result says
so — lexical matches are still real matches. An empty library or
a query with no matches answers honestly instead of inventing
entries.
"""
from __future__ import annotations

import logging
from pathlib import Path
from typing import Any

from aether_engine.config import UserConfig
from aether_engine.media.store import MediaStore, get_media_store
from aether_engine.memory import episodic
from aether_engine.tools.registry import Tool, ToolRisk

logger = logging.getLogger("aether_engine.tools.media_recall")

_MAX_LIMIT = 20


async def search_media_entries(
    query: str,
    *,
    limit: int = 5,
    collection: str = "all",
    store: MediaStore | None = None,
    config: UserConfig | None = None,
) -> dict[str, Any]:
    """Search the media index. Returns ``{results, degraded}``.

    Results are full media item dicts (file path, collection,
    summary, tags, session/message references) ranked by the
    store's hybrid RRF merge. ``degraded`` is True when the
    embedding endpoint was unavailable and ranking is lexical
    only.
    """
    limit = max(1, min(int(limit or 5), _MAX_LIMIT))
    if collection not in ("all", "user", "generated"):
        collection = "all"
    store = store if store is not None else get_media_store()
    query_vec = await episodic.embed_text(
        query, config=config, context="media_recall")
    degraded = query_vec is None
    results = store.search_media(
        query=query, query_vec=query_vec, limit=limit, collection=collection)
    return {"results": results, "degraded": degraded}


def format_media_results(query: str, outcome: dict[str, Any]) -> str:
    """Render a recall outcome as the tool's text for the agent."""
    results = outcome["results"]
    if not results:
        return (
            f"No matching media items found for {query!r}. The media "
            "library only contains media that was shared in chats or "
            "generated by tasks and then analysed — try different "
            "words for what the media shows."
        )
    lines = [f"{len(results)} media item(s) matching {query!r}:"]
    if outcome["degraded"]:
        lines.append(
            "(Semantic ranking is unavailable — the embedding endpoint "
            "is down — so these are lexical matches only.)")
    for i, r in enumerate(results, start=1):
        name = Path(r.get("file_path") or "").name or r.get("file_path") or "(unknown file)"
        tags = ", ".join(r.get("tags") or [])
        lines.append(
            f"\n[{i}] {name} ({r.get('media_type')}, {r.get('collection')})"
            f"\n    file: {r.get('file_path')}"
            f"\n    session: {r.get('session_id')} · message: {r.get('message_id')}"
            f"\n    summary: {r.get('summary_text') or '(no summary)'}"
            + (f"\n    tags: {tags}" if tags else "")
        )
    return "\n".join(lines)


async def _media_recall_fn(
    query: str,
    limit: int = 5,
    collection: str = "all",
) -> str:
    outcome = await search_media_entries(
        query, limit=limit, collection=collection)
    return format_media_results(query, outcome)


def create_media_recall_tool() -> Tool:
    return Tool(
        name="media_recall",
        description=(
            "Find media from earlier conversations — photos or videos "
            "the user shared, snips, and media generated by previous "
            "tasks — by describing what it shows (e.g. 'red bicycle', "
            "'diagram of database schema'). Returns matching entries "
            "with their file paths and the session/message they came "
            "from. Media is indexed by its analysed content, so "
            "describe the content, not the filename."
        ),
        input_schema={
            "type": "object",
            "properties": {
                "query": {
                    "type": "string",
                    "description": "What the media shows — objects, scene, topic, or text in it",
                },
                "limit": {
                    "type": "integer",
                    "description": "Maximum entries to return (default 5)",
                },
                "collection": {
                    "type": "string",
                    "enum": ["all", "user", "generated"],
                    "description": "Restrict to media the user shared ('user') or media generated by tasks ('generated'); default 'all'",
                },
            },
            "required": ["query"],
        },
        execute_fn=_media_recall_fn,
        risk=ToolRisk.READ_ONLY,
    )

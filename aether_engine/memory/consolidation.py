"""Epic 4, E4-10 (plan addendum omp #33, owner-approved 30 Oct
2026): periodic memory consolidation — the curated memory document.

A scheduled pass (weekly, registered next to retention pruning in
the capability scheduler, with a manual ``run_memory_consolidation_now``
trigger mirroring ``run_memory_prune_now``) renders the accumulated
episodic and knowledge-graph rows into one readable Markdown
document, ``~/.aether/curated_memory.md``, so long-term memory is
legible as a document, not just rows in two databases.

Guarantees, mirroring the stores it reads:

* **Current truth only.** The document is rendered from the
  facade's default views — active facts (superseded history is
  excluded by the retrieval contract) and current episode rows —
  so consolidation can never resurrect a superseded fact or a
  deleted episode, and it writes nothing back to any store.
* **Secret-redacted.** Every rendered string passes through the
  house redactor (the audit module's ``_scrub_string``, the same
  scrubber session export uses) before it reaches the document.
* **Capped.** The document is truncated to MAX_DOCUMENT_CHARS
  (~6k tokens at the usual 4-chars/token estimate) with an explicit
  truncation note — the cap is stated in the document itself.
* **Crash-safe.** The write is atomic (temp file in the same
  directory + fsync + ``os.replace``, the engine's file discipline
  from learned.py / config saves): a crash leaves the previous
  document intact.
"""
from __future__ import annotations

import logging
import os
import tempfile
import time
from pathlib import Path
from typing import Any

from aether_engine.audit import AuditLogger, _scrub_string
from aether_engine.config import UserConfig

_audit_logger = AuditLogger()

logger = logging.getLogger("aether_engine.memory.consolidation")

# The curated document lives beside learned.md and the memory DBs.
MEMORY_DOCUMENT_PATH = Path.home() / ".aether" / "curated_memory.md"

# Render bounds: how many rows the document draws on before the
# character cap governs, and the cap itself.
MAX_FACTS = 500
MAX_EPISODES = 100
MAX_DOCUMENT_CHARS = 24_000
_EPISODE_LINE_CHARS = 240

_TRUNCATION_NOTE = "\n\n_[Truncated to the consolidation size cap.]_\n"


def _fact_line(fact: dict[str, Any]) -> str:
    text = _scrub_string(str(fact.get("fact_text", "")).strip())
    bits = [f"- {text}"]
    confidence = fact.get("confidence")
    if confidence is not None:
        try:
            bits.append(f"(confidence {float(confidence):.2f})")
        except (TypeError, ValueError):
            pass
    return " ".join(bits)


def _episode_line(episode: dict[str, Any]) -> str:
    stamp = episode.get("timestamp")
    when = (
        time.strftime("%Y-%m-%d", time.gmtime(stamp)) if stamp else "unknown date"
    )
    summary = _scrub_string(
        str(episode.get("task_summary") or episode.get("outcome") or "").strip()
    )
    prompt = _scrub_string(str(episode.get("user_prompt", "")).strip())
    line = f"- {when} — {summary or prompt}"
    if len(line) > _EPISODE_LINE_CHARS:
        line = line[:_EPISODE_LINE_CHARS].rstrip() + "…"
    return line


def _render(facts: list[dict[str, Any]], episodes: list[dict[str, Any]]) -> str:
    generated = time.strftime("%Y-%m-%d %H:%M UTC", time.gmtime())
    intro = (
        f"Curated from the episodic and knowledge-graph stores on {generated}. "
        "Generated by the periodic consolidation pass (addendum omp #33) — "
        "edit the underlying memory, not this file."
    )
    parts = [
        "# Aether memory document",
        "",
        intro,
        "",
        f"## What Aether knows ({len(facts)} facts)",
        "",
    ]
    by_entity: dict[str, list[dict[str, Any]]] = {}
    for fact in facts:
        by_entity.setdefault(str(fact.get("entity_name") or "Unknown"), []).append(fact)
    if not by_entity:
        parts.append("_No facts stored yet._")
        parts.append("")
    for entity in sorted(by_entity, key=str.casefold):
        entity_facts = by_entity[entity]
        entity_type = str(entity_facts[0].get("entity_type") or "").strip()
        heading = f"### {entity}" + (f" ({entity_type})" if entity_type else "")
        parts.append(_scrub_string(heading))
        parts.extend(_fact_line(fact) for fact in entity_facts)
        parts.append("")
    parts.append(f"## Recent tasks ({len(episodes)} most recent)")
    parts.append("")
    if episodes:
        parts.extend(_episode_line(episode) for episode in episodes)
    else:
        parts.append("_No episodes stored yet._")
    parts.append("")
    return "\n".join(parts)


def _write_document(text: str, path: Path) -> None:
    """Atomically replace the document: a crash leaves either the
    old or the new document, never a truncated one."""
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp_name = tempfile.mkstemp(dir=path.parent, prefix=path.name, suffix=".tmp")
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as f:
            f.write(text)
            f.flush()
            os.fsync(f.fileno())
        os.replace(tmp_name, path)
    except BaseException:
        try:
            os.unlink(tmp_name)
        except OSError:
            pass
        raise


def consolidate_memory_document(
    config: UserConfig | None = None,
    path: Path | None = None,
) -> dict[str, Any]:
    """Run one consolidation pass and write the curated document.

    Reads through the memory facade (the configured backend's
    default views), so the document reflects the store the engine
    is actually using. An unavailable backend is an explicit
    ``written: False`` result with the reason — never a fabricated
    document and never an exception into the scheduler.
    """
    from aether_engine.memory.facade import backend_or_none

    target = path if path is not None else MEMORY_DOCUMENT_PATH
    backend = backend_or_none(config, context="memory consolidation")
    if backend is None:
        logger.warning("Memory consolidation skipped: backend unavailable")
        return {"written": False, "error": "memory backend unavailable"}

    facts = backend.list_facts(limit=MAX_FACTS)
    episodes = backend.list_episodes(limit=MAX_EPISODES)
    text = _render(facts, episodes)
    if len(text) > MAX_DOCUMENT_CHARS:
        text = text[: MAX_DOCUMENT_CHARS - len(_TRUNCATION_NOTE)] + _TRUNCATION_NOTE
    _write_document(text, target)

    result = {
        "written": True,
        "path": str(target),
        "facts": len(facts),
        "episodes": len(episodes),
        "chars": len(text),
    }
    _audit_logger.log_event("MEMORY_DOCUMENT_CONSOLIDATED", result)
    logger.info("MEMORY_DOCUMENT_CONSOLIDATED %s", result)
    return result
